def moma_center_max():
    """箱を水平に持って棚の通路側の面に出し入れするとき、箱の中心を上げられる最大の高さ。"""
    import math
    dz = MOMA_FACE - MOMA_TOOL + 20          # 肩から手首までの水平距離（棚の奥行き方向）
    return MOMA_J2_H + math.sqrt(max(0.0, MOMA_ARM ** 2 - dz ** 2 - MOMA_LAT ** 2))

